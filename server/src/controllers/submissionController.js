const axios = require("axios");
const Problem = require("../models/Problem");
const Submission = require("../models/Submission");
const User = require("../models/User");

const LANGUAGE_IDS = {
  cpp: 54,
  c: 50,
  python: 71,
  java: 62,
  javascript: 63,
};

exports.submitCode = async (req, res) => {
  try {
    const { code, language = "cpp", problemId, focusModeEnabled = false, hasOpenedHint = false, personalizedHintCount = 0 } = req.body;
    const language_id = LANGUAGE_IDS[language] || 54;
    // Clerk middleware normally puts the auth object in req.auth
    const userId = req.auth ? req.auth.userId : null;

    if (!problemId) {
      return res.status(400).json({ error: "Missing problemId" });
    }

    const problem = await Problem.findById(problemId);
    if (!problem) return res.status(404).json({ error: "Problem not found" });

    // Parse test cases from request or fallback to problem definition
    let testCases = req.body.testCases && req.body.testCases.length > 0 ? req.body.testCases : [];
    
    // 👑 Priority 1: Hidden robust test cases generated by the AI engine
    if (problem.testCases && problem.testCases.length > 0) {
      testCases = problem.testCases;
    }
    // Priority 2: req.body.testCases (frontend parsed public examples)
    // Priority 3: problem.examples (fallback string/array parsing)
    else if (testCases.length === 0 && problem.examples) {
      try {
        if (typeof problem.examples === "string") {
          testCases = JSON.parse(problem.examples);
        } else if (Array.isArray(problem.examples)) {
          testCases = problem.examples;
        }
      } catch (e) {
        console.warn("Failed to parse examples for problem", problemId);
      }
    }

    // Fallback if no test cases defined
    if (testCases.length === 0) {
      testCases = [{ input: "", output: "" }];
    }

    const judge0Url = process.env.JUDGE0_API_URL || "http://localhost:2358";

    let finalStatus = "Accepted";
    let maxTime = 0;
    let maxMemory = 0;
    let failedTestCase = null;
    let errorDetails = null;
    let passedCount = 0;
    const totalTestCases = testCases.length;

    let executionCode = code;
    if (problem.driverCode && problem.driverCode[language]) {
      console.log("[Submit] Found driver code for language:", language);
      if (problem.driverCode[language].includes("${USER_CODE_PLACEHOLDER}")) {
        executionCode = problem.driverCode[language].replace(
          "${USER_CODE_PLACEHOLDER}",
          code,
        );
        console.log("[Submit] Injected driver code successfully.");
      } else {
        console.warn("[Submit] Driver code is missing the ${USER_CODE_PLACEHOLDER} placeholder!");
        // Fallback: Try to extract main() from driverCode
        if (language === 'cpp') {
            if (problem.driverCode[language].includes("int main()")) {
                const mainPart = problem.driverCode[language].substring(problem.driverCode[language].indexOf("int main()"));
                executionCode = "#include <bits/stdc++.h>\nusing namespace std;\n\n" + code + "\n\n" + mainPart;
            } else {
                executionCode = "#include <bits/stdc++.h>\nusing namespace std;\n\n" + code + "\n\nint main() { return 0; }";
            }
        }
      }
    } else {
      console.warn("[Submit] No driver code found for language:", language, "(keys:", problem.driverCode ? Object.keys(problem.driverCode) : 'undefined', ")");
    }

    // Evaluate test cases in parallel batches to dramatically speed up execution while preventing Compilation TLE
    const BATCH_SIZE = 15;
    for (let i = 0; i < testCases.length; i += BATCH_SIZE) {
      const batch = testCases.slice(i, i + BATCH_SIZE);

      const batchPromises = batch.map(async (tc, indexInBatch) => {
        const stdin = (tc.input || "").trim();
        const expectedOutput = (tc.output || "").trim();
        const testCaseNumber = i + indexInBatch + 1;

        const b64 = (str) => Buffer.from(str || "").toString("base64");
        const dec = (str) =>
          str ? Buffer.from(str, "base64").toString("utf-8") : null;

        try {
          const response = await axios.post(
            `${judge0Url}/submissions?base64_encoded=true&wait=true`,
            {
              source_code: b64(executionCode),
              stdin: b64(stdin),
              language_id,
            },
            {
              headers: { "Content-Type": "application/json" },
              timeout: 60000,
            },
          );

          const { stdout, stderr, compile_output, message, status, time, memory } = response.data;
          return {
            testCaseNumber,
            stdin,
            expectedOutput,
            decodedStdout: dec(stdout),
            decodedStderr: dec(stderr),
            decodedCompile: dec(compile_output),
            message,
            status_id: status?.id,
            time: parseFloat(time) || 0,
            memory: memory || 0
          };
        } catch (err) {
          // Fallback for axios/network errors
          return {
            testCaseNumber,
            stdin,
            expectedOutput,
            status_id: 13, // Internal Error
            message: err.message,
            time: 0,
            memory: 0
          };
        }
      });

      // Wait for the entire batch of 15 test cases to finish
      const results = await Promise.all(batchPromises);

      // Evaluate results sequentially to maintain accurate pass counts and break on first failure
      for (const res of results) {
        if (res.time > maxTime) maxTime = res.time;
        if (res.memory > maxMemory) maxMemory = res.memory;

        // Check for Errors (CE, RE, TLE)
        if (res.status_id && res.status_id !== 3) {
          if (res.status_id === 6) finalStatus = "Compilation Error";
          else if (res.status_id === 5) finalStatus = "Time Limit Exceeded";
          else if (res.status_id >= 7 && res.status_id <= 12)
            finalStatus = "Runtime Error";
          else finalStatus = "Internal Error";

          errorDetails = res.decodedCompile || res.decodedStderr || res.message || "Error occurred";
          break;
        }

        // Check if output matches expected (only if expected is truthy)
        if (res.expectedOutput) {
          const actualOutput = (res.decodedStdout || "").trim();
          if (actualOutput !== res.expectedOutput) {
            finalStatus = "Wrong Answer";
            failedTestCase = {
              testCaseNumber: res.testCaseNumber,
              input: res.stdin,
              expected: res.expectedOutput,
              actual: actualOutput,
            };
            break;
          }
        }

        // This test case passed
        passedCount++;
      }

      // If any test case in this batch failed, break the outer loop immediately to save compute
      if (finalStatus !== "Accepted") {
        break;
      }
    }

    // Save Submission with test case info
    const submission = await Submission.create({
      userId,
      problemId,
      code,
      language,
      status: finalStatus,
      executionTime: maxTime,
      memory: maxMemory,
      passedTestCases: passedCount,
      totalTestCases: totalTestCases,
    });

    // Update User Progress if Accepted
    let pointsEarned = null;
    if (finalStatus === "Accepted" && userId) {
      const user = await User.findOne({ clerkId: userId });
      if (user) {
        // Use MongoDB _id for tracking solved problems (more reliable)
        const problemIdStr = problem._id.toString();
        const alreadySolved = user.solvedProblems.find(
          (p) =>
            p.problemId === problemIdStr || p.problemId === problem.problemId,
        );
        if (!alreadySolved) {
          // Points logic
          pointsEarned = { base: 10, focusBonus: 0, streakBonus: 0, hintPenalty: 0, total: 10 };
          
          if (focusModeEnabled && !hasOpenedHint) {
            pointsEarned.focusBonus = 5;
            pointsEarned.total += 5;
          }

          // Personalized hint penalty: -1 point per use in Focus Mode (min 0)
          if (focusModeEnabled && personalizedHintCount > 0) {
            const penalty = Math.min(personalizedHintCount, pointsEarned.total);
            pointsEarned.hintPenalty = penalty;
            pointsEarned.total = Math.max(0, pointsEarned.total - penalty);
          }

          // Streak Bonus Logic with 4 AM Rollover
          const logicalToday = new Date(Date.now() - 4 * 60 * 60 * 1000);
          const todayDateKey = logicalToday.toISOString().split('T')[0];
          
          // Check if they already solved something today
          const hasSolvedToday = user.solvedProblems.some(p => {
             const d = new Date(new Date(p.solvedAt).getTime() - 4 * 60 * 60 * 1000);
             return d.toISOString().split('T')[0] === todayDateKey;
          });

          if (!hasSolvedToday) {
             // Calculate current streak from solvedProblems
             // Extract unique logical dates
             const uniqueDates = [...new Set(user.solvedProblems.map(p => {
               const d = new Date(new Date(p.solvedAt).getTime() - 4 * 60 * 60 * 1000);
               return d.toISOString().split('T')[0];
             }))].sort((a, b) => new Date(b) - new Date(a));
             
             let streak = 0;
             if (uniqueDates.length > 0) {
                const logicalYesterday = new Date(Date.now() - 4 * 60 * 60 * 1000);
                logicalYesterday.setDate(logicalYesterday.getDate() - 1);
                const yesterdayDateKey = logicalYesterday.toISOString().split('T')[0];
                
                // If they solved yesterday, calculate from yesterday backwards
                if (uniqueDates[0] === yesterdayDateKey) {
                   streak = 0;
                   const checkDate = new Date(logicalYesterday);
                   for(let i=0; i<uniqueDates.length; i++) {
                     const dStr = checkDate.toISOString().split('T')[0];
                     if(uniqueDates[i] === dStr) {
                       streak++;
                       checkDate.setDate(checkDate.getDate() - 1);
                     } else {
                       break;
                     }
                   }
                }
             }
             
             // This submission makes the streak increase by 1
             const newStreak = streak + 1;
             
             // Check formula: S = 2n^2 + 1 => n = sqrt((S-1)/2)
             if ((newStreak - 1) % 2 === 0) {
               const n = Math.sqrt((newStreak - 1) / 2);
               if (Number.isInteger(n) && n > 0) {
                 pointsEarned.streakBonus = n;
                 pointsEarned.total += n;
               }
             }
          }

          user.points = (user.points || 0) + pointsEarned.total;

          user.solvedProblems.push({
            problemId: problemIdStr,
            title: problem.title || "",
            platform: problem.platform || "LeetCode",
            pointsEarned: pointsEarned.total,
            focusMode: focusModeEnabled && !hasOpenedHint,
            solvedAt: new Date(),
          });
          await user.save();
        }
      }
    }

    res.json({
      submissionId: submission._id,
      status: finalStatus,
      time: maxTime,
      memory: maxMemory,
      passedTestCases: passedCount,
      totalTestCases: totalTestCases,
      failedTestCase,
      errorDetails,
      pointsEarned,
    });
  } catch (error) {
    console.error("[Submit] Error:", error.message);
    res.status(500).json({ error: error.message });
  }
};

// Get submission history for a problem
exports.getSubmissions = async (req, res) => {
  try {
    const { problemId } = req.params;
    const userId = req.auth ? req.auth.userId : null;

    if (!userId) {
      return res.json({ submissions: [] });
    }

    const submissions = await Submission.find({
      problemId,
      userId,
    })
      .sort({ createdAt: -1 })
      .limit(20)
      .select(
        "status language executionTime memory passedTestCases totalTestCases createdAt code",
      );

    res.json({ submissions });
  } catch (error) {
    console.error("[GetSubmissions] Error:", error.message);
    res.status(500).json({ error: error.message });
  }
};

// Get a single submission with code
exports.getSubmissionById = async (req, res) => {
  try {
    const { submissionId } = req.params;
    const userId = req.auth ? req.auth.userId : null;

    const submission = await Submission.findById(submissionId);

    if (!submission) {
      return res.status(404).json({ error: "Submission not found" });
    }

    // Only return code if it's the user's submission
    if (submission.userId !== userId) {
      return res.status(403).json({ error: "Access denied" });
    }

    res.json({ submission });
  } catch (error) {
    console.error("[GetSubmissionById] Error:", error.message);
    res.status(500).json({ error: error.message });
  }
};
